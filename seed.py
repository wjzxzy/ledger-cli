    s = db.summary()
    print(f"已灌入 {len(DEMO)} 条")
    print(f"总计 {s['total_count']} 笔，{s['total_amount']:.2f} 元")
    for row in s["by_category"]:
        print(f"  {row['category']:<4} {row['cnt']:>2} 笔  {row['amount']:>8.2f} 元")


